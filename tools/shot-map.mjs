// Шрифт 5×7 — минимальный, чтобы текст был читаемым в PNG.
function drawChar(ch, x, y, col) {
  const g = FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT['?'];
  for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '1') put(x + c, y + r, ...col);
}
const textW = (t) => t.length * 6;
function drawText(t, x, y, col) {
  let cx = Math.round(x - textW(t) / 2);
  for (const ch of t) { drawChar(ch, cx, Math.round(y - 3.5), col); cx += 6; }
}

