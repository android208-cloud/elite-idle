/* ---------- Матрица поворота ---------- */

/**
 * Матрица поворота 3×3 из трёх углов (Эйлер, порядок ZYX).
 * Возвращает функцию (v) => повёрнутый вектор, чтобы не плодитьаллокации
 * в кадре: считаем матрицу один раз на кадр.
 *
 * yaw   — рыскание (вокруг Y), «поворот носа влево/вправо»
 * pitch — тангаж (вокруг X), «нос вверх/вниз»
 * roll  — крен (вокруг Z), «бочка»
 */
export function rotationMatrix(yaw, pitch, roll) {
  const cy = Math.cos(yaw), sy = Math.sin(yaw);
  const cp = Math.cos(pitch), sp = Math.sin(pitch);
  const cr = Math.cos(roll), sr = Math.sin(roll);

  // R = Rz(roll) · Ry(yaw) · Rx(pitch)
  const m00 = cr * cy - sr * sp * sy;
  const m01 = sr * cy + cr * sp * sy;
  const m02 = -cp * sy;

  const m10 = -sr * cp;
  const m11 = cr * cp;
  const m12 = sp;

  const m20 = cr * sy + sr * sp * cy;
  const m21 = sr * sy - cr * sp * cy;
  const m22 = cp * cy;

  return (v) => [
    m00 * v[0] + m01 * v[1] + m02 * v[2],
    m10 * v[0] + m11 * v[1] + m12 * v[2],
    m20 * v[0] + m21 * v[1] + m22 * v[2],
  ];
}

/* ---------- Проекция ---------- */

/**
 * Перспективная проекция точки камеры на экран.
 *
 * @param p       точка в системе координат камеры (после поворота и сдвига)
 * @param fov     фокусное расстояние в пикселях
 * @param cx,cy   центр экрана
 * @returns       {x, y, z} — экранные координаты и глубина (z > 0 перед камерой)
 */
export function project(p, fov, cx, cy) {
  const z = p[2];
  // Точки за камерой или вплотную к ней не проецируем — отдаём z<=0,
  // вызывающий код такие вершины отбрасывает.
  if (z <= 0.5) return { x: 0, y: 0, z };
  const k = fov / z;
  return { x: cx + p[0] * k, y: cy + p[1] * k, z };
}

/* ---------- Проверка формы (для тестов) ---------- */

/**
 * Все 12 «телесных» вершин лежат на гранях кубооктаэдра:
 * две координаты по модулю равны радиусу, третья — ноль.
 */
export function isCuboctahedron(vertices = VERTICES) {
  for (let i = 0; i < 12; i++) {
    const a = vertices[i].map(Math.abs).sort((p, q) => q - p);
    if (a[0] !== STATION_RADIUS || a[1] !== STATION_RADIUS || a[2] !== 0) return false;
  }
  const seen = new Set(vertices.slice(0, 12).map((v) => v.join(',')));
  return seen.size === 12;
}
