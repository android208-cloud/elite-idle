/**
 * Кориолис — геометрия станции из оригинального Elite.
 *
 * Источник: `reference/zx-elite-ataribaby/src/data/ship-blueprints-and-tables.asm`
 *   ShipCoriolisStationBlueprint  ($6BE1)
 *   ShipCoriolisStationVertices   ($6AB4) — 96 байт = 16 вершин × 6 байт
 *   ShipCoriolisStationEdges      ($6B14) — 28 рёбер × 4 байта
 *
 * Формат вершины (важно, с первого раза не угадывается):
 *   байт 0: |X| (маска $7F)
 *   байт 1: |Y|
 *   байт 2: |Z|
 *   байт 3: знаки + порог видимости
 *           бит 7 = знак X, бит 6 = знак Y, бит 5 = знак Z
 *           биты 0..4 = порог ($1F = видна на любой дистанции)
 *   байт 4, 5: пары граней (по две в каждом)
 *
 * Радиус станции: 32 единицы. Радиус в blueprint (+1) = 160 — это для
 * столкновений, а не для отрисовки.
 *
 * Формат ребра: [вершина1, вершина2] — байты 0 и 1 таблицы.
 * (Байты 2–3 — грани для теста видимости, для каркаса нужны не всегда.)
 */

/* ---------- Вершины ---------- */

const VERTEX_BYTES = [
  0xA0, 0x00, 0xA0, 0x1F, 0x10, 0x62, // 0  ( 32,   0,  32)
  0x00, 0xA0, 0xA0, 0x1F, 0x20, 0x83, // 1  (  0,  32,  32)
  0xA0, 0x00, 0xA0, 0x9F, 0x30, 0x74, // 2  (-32,   0,  32)
  0x00, 0xA0, 0xA0, 0x5F, 0x10, 0x54, // 3  (  0, -32,  32)
  0xA0, 0xA0, 0x00, 0x5F, 0x51, 0xA6, // 4  ( 32, -32,   0)
  0xA0, 0xA0, 0x00, 0x1F, 0x62, 0xB8, // 5  ( 32,  32,   0)
  0xA0, 0xA0, 0x00, 0x9F, 0x73, 0xC8, // 6  (-32,  32,   0)
  0xA0, 0xA0, 0x00, 0xDF, 0x54, 0x97, // 7  (-32, -32,   0)
  0xA0, 0x00, 0xA0, 0x3F, 0xA6, 0xDB, // 8  ( 32,   0, -32)
  0x00, 0xA0, 0xA0, 0x3F, 0xB8, 0xDC, // 9  (  0,  32, -32)
  0xA0, 0x00, 0xA0, 0xBF, 0x97, 0xDC, // 10 (-32,   0, -32)
  0x00, 0xA0, 0xA0, 0x7F, 0x95, 0xDA, // 11 (  0, -32, -32)
  0x0A, 0x1E, 0xA0, 0x5E, 0x00, 0x00, // 12 ( 10, -30,  32) шлюз
  0x0A, 0x1E, 0xA0, 0x1E, 0x00, 0x00, // 13 ( 10,  30,  32) шлюз
  0x0A, 0x1E, 0xA0, 0x9E, 0x00, 0x00, // 14 (-10,  30,  32) шлюз
  0x0A, 0x1E, 0xA0, 0xDE, 0x00, 0x00, // 15 (-10, -30,  32) шлюз
];

/**
 * Расшифровка таблицы вершин в массив [x, y, z].
 * Знаки хранятся в третьем байте: бит 7 = X, бит 6 = Y, бит 5 = Z.
 */
export const VERTICES = (() => {
  const out = [];
  for (let i = 0; i < VERTEX_BYTES.length; i += 6) {
    const mx = VERTEX_BYTES[i] & 0x7f;
    const my = VERTEX_BYTES[i + 1] & 0x7f;
    const mz = VERTEX_BYTES[i + 2] & 0x7f;
    const signs = VERTEX_BYTES[i + 3];
    out.push([
      signs & 0x80 ? -mx : mx,
      signs & 0x40 ? -my : my,
      signs & 0x20 ? -mz : mz,
    ]);
  }
  return out;
})();

