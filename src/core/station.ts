/**
 * §125: СКОЛЬКО СТОИТ СТАНЦИЯ.
 *
 * Пользователь: «сколько может стоить классическая станция (не планета),
 * можно ли вывести цену по каким-то формулам самой игры?» — и затем:
 * «можно попробовать увязать все вводные станции без привязки к кораблям?»
 *
 * В Elite станции не продаются, готовой цены в формулах нет. Но размер у
 * станции измерен честно, и денежная опора тоже есть внутри неё самой:
 * СКЛАД УЖЕ В КРЕДИТАХ. Поэтому ссылаться на цену Анаконды не нужно — в
 * отличие от шкалы кораблей (§102) здесь нет внешнего якоря.
 *
 * Три актива, все три — из данных системы:
 *
 *   1. Полки — стоимость товара на станции, Σ(цена × количество).
 *      Оборотный капитал: 5 811 … 16 972 CR по галактике 1.
 *   2. Производство — `productivity`, выпуск в сутки. Единственная мера
 *      размера мира с настоящим разбросом: 768 … 56 320.
 *   3. Земля и порядок — `government` (0…7): чем крепче собственность,
 *      тем дороже недвижимость. В анархии станция дешевле, и это не
 *      поблажка, а скидка за риск.
 *
 * Цена = 10 × (4 · склад + 0.2 · выпуск · (техуровень + 1) + 0.5 · склад · порядок)
 *
 * Про множитель 10: пользователь сказал «добавим „0“ к цене, ведь это
 * станция, а не корабль». Он прав по сути — станция это город, а не
 * транспорт, — и множитель стоит отдельной константой, чтобы это было
 * видно, а не растворялось в коэффициентах.
 *
 * Почему каждая вводная ровно один раз (иначе получился бы двойной счёт):
 *   • экономика уже сидит в складе (от неё зависит количество товара)
 *     и в выпуске;
 *   • население уже сидит в выпуске: prod = ((eco^7)+3)·(gov+4)·pop·8;
 *   • техуровень попадает в выпуск только через население, поэтому как
 *     «цена железа» он взят отдельным множителем — это другая величина;
 *   • порядок работает двумя каналами: организованность → выпуск и
 *     безопасность собственности → надбавка к земле. Это разные вещи.
 *
 * Что получается (галактика 1, 256 систем): 238 100 … 2 962 500 CR,
 * медиана 713 800. LAVE — 477 400, CEESXE — 2 962 500.
 */
import type { StarSystem } from './galaxy.ts';
import { generateMarket } from './market.ts';

/**
 * Во сколько раз станция дороже собственного имущества.
 *
 * Пользователь: «добавим „0“ к цене, ведь это станция, а не корабль».
 * Без множителя станция выходила дешевле Анаконды, что для города абсурд.
 */
export const STATION_SCALE = 10;

/** Округление цены: на таких суммах кредиты до копейки — шум. */
export const STATION_ROUND = 100;

/**
 * Стоимость товара на полках станции в кредитах.
 *
 * Берём рынок без колебаний (`fluct = 0`): цена станции не должна дёргаться
 * от того, что игрок только что продал партию. Это оценка имущества, а не
 * котировка.
 */
export function stationStockValue(system: StarSystem): number {
  const market = generateMarket(system, 0);
  let tenths = 0;
  for (const entry of market) tenths += entry.price * entry.quantity;
  return tenths / 10;
}

/**
 * Цена классической станции в кредитах.
 *
 * Чистая функция от системы: одинакова у всех игроков с той же галактикой,
 * не зависит от денег и ранга игрока и не требует места в сейве — её можно
 * считать на лету и показывать в карточке системы.
 */
export function stationPrice(system: StarSystem): number {
  const stock = stationStockValue(system);
  const shelves = 4 * stock;
  const industry = 0.2 * system.productivity * (system.techLevel + 1);
  const land = 0.5 * stock * system.government;
  const base = shelves + industry + land;
  return Math.round((base * STATION_SCALE) / STATION_ROUND) * STATION_ROUND;
}
