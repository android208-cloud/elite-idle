/**
 * Выпуклая оболочка точек (алгоритм Эндрю, монотонная цепь).
 *
 * Зачем: у днища корпуса 21 вершина, но **14 из них внутренние** —
 * они лежат внутри контура, а не на нём. Сортировка по углу вокруг
 * центра даёт для такого набора самопересекающийся полигон, и
 * заливка оставляет «чёрные дыры»: именно их пользователь видел как
 * «прозрачность и не хватает граней».
 *
 * Оболочка отбрасывает внутренние вершины, полигон остаётся простым.
 */
/** Площадь многоугольника по формуле шнуровки (знак — направление обхода). */
function polygonArea(pts: readonly { x: number; y: number }[]): number {
  let s = 0;
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i];
    const b = pts[(i + 1) % pts.length];
    s += a.x * b.y - b.x * a.y;
  }
  return s / 2;
}

function convexHull(points: { x: number; y: number }[]): { x: number; y: number }[] {
  if (points.length < 3) return [...points];
  const sorted = [...points].sort((a, b) => a.x - b.x || a.y - b.y);
  const cross = (o: { x: number; y: number }, a: { x: number; y: number }, b: { x: number; y: number }): number =>
    (a.x - o.x) * (b.y - o.y) - (a.y - o.y) * (b.x - o.x);

  const lower: { x: number; y: number }[] = [];
  for (const p of sorted) {
    while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) lower.pop();
    lower.push(p);
  }
  const upper: { x: number; y: number }[] = [];
  for (let i = sorted.length - 1; i >= 0; i--) {
    const p = sorted[i];
    while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) upper.pop();
    upper.push(p);
  }
  lower.pop();
  upper.pop();
  return [...lower, ...upper];
}

/**
 * Доли кадра, которые модель занимает по горизонтали и по вертикали.
 *
 * Разные, потому что холст не квадратный, а корабли плоские и
 * вытянутые: подгонка по одной стороне оставляла бы половину кадра
 * пустой. Запас в 6–12% — на вращение: за оборот модель поворачивается
 * всеми боками, и в самом широком ракурсе не должна упираться в край.
 */
const FIT_WIDTH = 0.92;
const FIT_HEIGHT = 0.86;

export interface ShipModelOptions {
  /** Размер холста в CSS-пикселях. */
  width: number;
  height: number;
  /** Угол поворота вокруг вертикальной оси, радианы. */
  yaw: number;
  /**
   * Какой корабль рисовать. По умолчанию — Cobra Mk III, корабль игрока.
   * Модели всего парка лежат в FLEET.
   */
  ship?: ShipBlueprint;
  /** Угол наклона, радианы. Небольшой, чтобы читался силуэт сверху. */
  pitch?: number;
  /** Цвет «носа» — чтобы было видно, куда корабль смотрит. */
  accent?: string;
}

/**
 * Рисует корабль в перспективе.
 *
 * Простая перспектива: чем дальше точка, тем ближе к центру. Без неё
 * рёбра дальней стороны наезжают на ближние и силуэт читается хуже.
 */
export function drawShipModel(ctx: CanvasRenderingContext2D, o: ShipModelOptions): void {
  const { width, height, yaw } = o;
  const pitch = o.pitch ?? 0.28;
  const accent = o.accent ?? '#ffd37a';

  // Геометрия: по умолчанию корабль игрока. Все дальнейшие шаги
  // одинаковы для любого корабля парка — меняются только таблицы.
  const bp: ShipBlueprint = o.ship ?? {
    name: 'Cobra Mk III',
    verts: PLAYER_VERTICES,
    edges: PLAYER_EDGES,
    faces: PLAYER_FACES,
  };
  const verts = bp.verts;
  const faces = bp.faces;
  // §110: рёбра (`bp.edges`) больше не рисуются — корпус заливается
  // гранями. Сами данные остаются: по ним извлекаются грани и их
  // проверяет tools/render-fleet.mjs.

  /* Центр модели: не (0,0,0), а середина габарита. У Python и Anaconda
   * корпус вытянут далеко назад (−112 и −58 при длине 336 и 312), и
   * вращение вокруг начала координат уводило модель из кадра. */
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity, minZ = Infinity, maxZ = -Infinity;
  for (const v of verts) {
    if (v[0] < minX) minX = v[0];
    if (v[0] > maxX) maxX = v[0];
    if (v[1] < minY) minY = v[1];
    if (v[1] > maxY) maxY = v[1];
    if (v[2] < minZ) minZ = v[2];
    if (v[2] > maxZ) maxZ = v[2];
  }
  const center: [number, number, number] = [(minX + maxX) / 2, (minY + maxY) / 2, (minZ + maxZ) / 2];

  const cy = Math.cos(yaw), sy = Math.sin(yaw);
  const cp = Math.cos(pitch), sp = Math.sin(pitch);

  /*
   * Масштаб подгоняется по ФАКТИЧЕСКОМУ силуэту, а не по константе.
   *
   * Было `0.0072` — число, подобранное под Cobra Mk III на холсте
   * 480×240. На 12 других кораблях оно не работает: Anaconda (312
   * единиц) вылезает за кадр, Adder (80) выходит мошкой.
   *
   * Поэтому: повернуть модель, измерить размах проекции, и взять
   * масштаб такой, чтобы силуэт занял 82% меньшей стороны холста.
   * Честно для любой формы и любого угла — узкая Mamba и длинный
   * Python влезают целиком.
   */
  const dist = 620; // «расстояние до камеры» в единицах модели
  const cx = width / 2;
  const cyy = height / 2;

  // Повёрнутые координаты — считаем один раз, они нужны дважды:
  // для подгонки масштаба и для самой проекции.
  const rotated = verts.map(([rvx, rvy, rvz]) => {
    const vx = rvx - center[0];
    const vy = rvy - center[1];
    const vz = rvz - center[2];
    const x1 = vx * cy + vz * sy;
    const z1 = -vx * sy + vz * cy;
    const y2 = vy * cp - z1 * sp;
    const z2 = vy * sp + z1 * cp;
    return { x: x1, y: y2, z: z2 };
  });

  // Размах проекции при scale = 1 (перспектива учитывается: дальние
  // точки меньше, поэтому масштаб по ближайшим, а не по «средним»).
  let extX = 1e-6, extY = 1e-6;
  for (const r of rotated) {
    const k = dist / (r.z + dist);
    extX = Math.max(extX, Math.abs(r.x * k) * 2);
    extY = Math.max(extY, Math.abs(r.y * k) * 2);
  }
  // Подгоняем по обеим осям и берём меньший масштаб: так модель
  // влезает целиком и при этом занимает кадр максимально возможного размера.
  const scale = Math.min((width * FIT_WIDTH) / extX, (height * FIT_HEIGHT) / extY);

  type Projected = { x: number; y: number; depth: number };
  const projected: Projected[] = [];

  for (const r of rotated) {
    const k = (dist / (r.z + dist)) * scale;
    projected.push({ x: cx + r.x * k, y: cyy + r.y * k, depth: r.z });
  }

  /*
   * Корабль рисуется ЗАЛИТЫМИ гранями, а не каркасом.
   *
   * Почему: каркас без скрытия — клубок. Скрытие одних только рёбер
   * помогало не полностью: у части углов дальние грани просвечивали
   * между ближними, и корпус выглядел прозрачным. Пользователь это
   * и увидел: «всё равно прозрачная и многих граней не хватает».
   *
   * Как рисуем:
   *  1. все 13 граней проецируются;
   *  2. каждая заливается своим тоном с учётом освещения;
   *  3. сортировка по средней глубине: дальние раньше, ближние позже —
   *     painter's algorithm. Для выпуклого тела этого достаточно:
   *     ближняя грань всегда перекрывает дальнюю;
   *  4. §110: НИКАКИХ линий поверх заливки. Рёбра раньше обводились:
   *     сначала ярким бирюзовым (§69), потом тёмным (§109). Пользователь
   *     дважды говорил одно и то же — «уберите окантовку», а потом
   *     «мигают некоторые рёбра». Это была одна и та же линия: тонкая
   *     обводка при вращении ползёт по пикселям, и антиалиасинг то
   *     показывает её, то прячет. Линия убрана совсем — корпус читается
   *     заливкой граней и светом, как вырезанная из бумаги модель.
   *
   * Проекция перспективная, поэтому перекрытие получается честным:
   * дальняя часть корпуса меньше и «прячется» за ближней.
   */

  // Нормали всех граней в исходных координатах — для освещения.
  const faceData = faces.map((faceVerts) => {
    const pts3 = faceVerts.map((i) => verts[i]);
    // Центр грани.
    const c3: [number, number, number] = [0, 0, 0];
    for (const p of pts3) {
      c3[0] += p[0] / pts3.length;
      c3[1] += p[1] / pts3.length;
      c3[2] += p[2] / pts3.length;
    }
    // Нормаль по первым трём вершинам.
    const [a, b, c] = pts3;
    const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    const w = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
    let n: [number, number, number] = [
      u[1] * w[2] - u[2] * w[1],
      u[2] * w[0] - u[0] * w[2],
      u[0] * w[1] - u[1] * w[0],
    ];
    const nl = Math.hypot(n[0], n[1], n[2]) || 1;
    n = [n[0] / nl, n[1] / nl, n[2] / nl];
    // Наружу: от центра габарита модели. Раньше здесь была жёсткая
    // точка (0, 0, 10) — годная для Cobra, но у вытянутых кораблей
    // она оказывалась у одного из торцов, и часть граней выворачивалась.
    const outward =
      (c3[0] - center[0]) * n[0] + (c3[1] - center[1]) * n[1] + (c3[2] - center[2]) * n[2];
    if (outward < 0) n = [-n[0], -n[1], -n[2]];
    return { verts: faceVerts, c3, n3: n };
  });

  // Повороты нормалей тем же преобразованием, что и вершин.
  const rotN = faceData.map(({ n3 }) => {
    const x1 = n3[0] * cy + n3[2] * sy;
    const z1 = -n3[0] * sy + n3[2] * cy;
    const y2 = n3[1] * cp - z1 * sp;
    const z2 = n3[1] * sp + z1 * cp;
    return { x: x1, y: y2, z: z2 };
  });

  // Свет: сверху-слева-спереди.
  const light = { x: -0.45, y: 0.75, z: 0.55 };
  const ll = Math.hypot(light.x, light.y, light.z);

  // Порядок: дальние грани рисуем первыми.
  const order = faceData
    .map((f, i) => {
      const pts = f.verts.map((vi) => projected[vi]);
      const depth = pts.reduce((acc, p) => acc + p.depth, 0) / pts.length;
      return { i, pts, depth, n: rotN[i] };
    })
    .sort((p, q) => p.depth - q.depth);

  /*
   * Базовый цвет корпуса.
   *
   * Было [20, 58, 54] при shade 0.35 → самая тёмная грань rgb(7, 20, 19),
   * а фон — rgb(11, 20, 18). Грань оказывалась ТЕМНЕЕ фона, и это
   * читалось как дыра в корпусе — ровно то, на что жаловался
   * пользователь.
   *
   * Теперь база светлее, а минимальная яркость поднята до 0.55:
   * любая грань заведомо светлее подложки и фона.
   */
  const baseRGB = [26, 74, 68] as const;

  /*
   * ШАГ 1: заливаем СИЛУЭТ корпуса целиком.
   *
   * Зачем, если дальше рисуются грани: при некоторых углах грань
   * повёрнута почти ребром (n.z ≈ 0) и отбрасывается как «отвёрнутая»,
   * хотя именно она закрывает часть корпуса. Тогда между гранями
   * оставались чёрные дыры, и корпус выглядел прозрачным.
   *
   * Заливка выпуклой оболочки ВСЕХ вершин гарантирует, что внутри
   * силуэта не будет ни одного незакрашенного пикселя — при любом угле.
   * Это дешёво (одна фигура) и снимает весь класс этих дыр.
   */
  const silhouette = convexHull(projected.map((p) => ({ x: p.x, y: p.y })));
  if (silhouette.length >= 3) {
    ctx.beginPath();
    ctx.moveTo(silhouette[0].x, silhouette[0].y);
    for (let i = 1; i < silhouette.length; i++) ctx.lineTo(silhouette[i].x, silhouette[i].y);
    ctx.closePath();
    // Тёмный корпус: чуть темнее самой тёмной грани.
    // Заметно светлее фона (rgb 11,20,18), но темнее любой грани.
    ctx.fillStyle = 'rgb(17, 46, 42)';
    ctx.fill();
  }

  /*
   * ШАГ 2: грани поверх силуэта.
   *
   * Отбрасываем только грани, смотрящие строго от зрителя (n.z < -0.05).
   * Грани «в профиль» (|n.z| мал) оставляем: они дают тонкие полосы
   * вдоль силуэта и без них корпус теряет объём.
   */
  for (const face of order) {
    /*
     * Отвёрнутые грани НЕ рисуем вовсе.
     *
     * Сначала я заливал их почти чёрным — «чтобы формировали силуэт
     * изнутри». На деле это и давало чёрные дыры в корпусе: при
     * некоторых углах такая грань оказывалась ближе лицевых и
     * закрывала их. Пользователь видел это как «прозрачность и не
     * хватает граней».
     *
     * Для выпуклого тела back-face culling — правильное решение:
     * лицевые грани покрывают весь силуэт, отвёрнутые не видны
     * в принципе.
     */
    if (face.n.z < -0.05) continue;

    const facing = true;
    const lambert = Math.max(
      0,
      (face.n.x * light.x + face.n.y * light.y + face.n.z * light.z) / ll,
    );
    // Минимум 0.55, а не 0.35: иначе грань уходила темнее фона.
    const shade = 0.55 + 0.45 * lambert;
    const r = Math.round(baseRGB[0] * shade);
    const g = Math.round(baseRGB[1] * shade);
    const b = Math.round(baseRGB[2] * shade);

    // Заливаем по ВЫПУКЛОЙ ОБОЛОЧКЕ, а не по всем вершинам.
    //
    // У днища 21 вершина, из которых 14 внутренние. Сортировка по углу
    // вокруг центра строит для них самопересекающийся полигон, и
    // заливка оставляет чёрные дыры — та самая «прозрачность».
    // Оболочка отбрасывает внутренние точки, полигон остаётся простым.
    const hull = convexHull(face.pts);
    if (hull.length < 3) continue;

    /*
     * §110: ГРАНЬ В ПИКСЕЛЬ — НЕ ГРАНЬ.
     *
     * Пользователь: «на модели корабля мигают некоторые ребра». Мигают
     * не рёбра, а грани, повёрнутые к зрителю почти ребром: их проекция —
     * полоска шириной в пиксель. При повороте такая полоска то
     * появляется (антиалиасинг накрывает соседнюю грань светлой или
     * тёмной линией), то исчезает — и это читается как дрожащее ребро.
     *
     * Отсекаем по ПЛОЩАДИ проекции, а не по углу: важно не то, насколько
     * грань отвернулась, а то, сколько пикселей она закрасит. Дыры от
     * этого быть не может — под гранями уже залит силуэт корпуса.
     */
    if (Math.abs(polygonArea(hull)) < 2) continue;

    ctx.beginPath();
    ctx.moveTo(hull[0].x, hull[0].y);
    for (let i = 1; i < hull.length; i++) ctx.lineTo(hull[i].x, hull[i].y);
    ctx.closePath();
    ctx.fillStyle = `rgb(${r}, ${g}, ${b})`;
    ctx.fill();
    /*
     * Шов между гранями.
     *
     * Две соседние грани заливаются с антиалиасингом — каждая чуть не
     * доходит до общей линии, и между ними остаётся волосяная щель цвета
     * подложки. Когда модель стоит, её не видно; при вращении щель ползёт
     * по пикселям и мигает. Обводим полигон той же краской в 1 px: щель
     * закрывается изнутри, а граница с соседом остаётся ровной.
     */
    ctx.strokeStyle = ctx.fillStyle;
    ctx.lineWidth = 1;
    ctx.stroke();

    // Контура у грани нет: корпус читается заливкой и светом, а не
    // линиями. Почему так — в §110 (см. ниже в файле и в шапке модуля).
  }

  /*
   * Нос — точка, чтобы было видно, куда корабль смотрит.
   *
   * Раньше здесь стояли жёстко вершины 20 и 21: у Cobra Mk III это
   * кончик носа (z = 76 и 90). У Sidewinder всего 10 вершин, и
   * projected[21] не существует — рендер падал с «undefined.x».
   * У Python вершина 20 — это днище, и точка оказывалась снизу.
   *
   * Теперь нос ищется по геометрии: вершина с наибольшим z (в
   * исходных координатах корабли смотрят в +z) среди тех, что ближе
   * всего к оси симметрии — иначе кончиком «крыла» окажется угол
   * размаха, а не нос.
   */
  let noseIdx = 0;
  let bestZ = -Infinity;
  for (let i = 0; i < verts.length; i++) {
    const v = verts[i];
    // Близко к оси X: нос у всех кораблей парка на оси.
    if (Math.abs(v[0] - center[0]) > 12) continue;
    if (v[2] > bestZ) {
      bestZ = v[2];
      noseIdx = i;
    }
  }
  const nose = projected[noseIdx];
  if (nose) {
    ctx.fillStyle = accent;
    ctx.beginPath();
    ctx.arc(nose.x, nose.y, 2.2, 0, Math.PI * 2);
    ctx.fill();
  }
}

