/**
 * §89: что показывать в верхней строке.
 *
 * Вынесено из `main.ts` в чистый модуль по двум причинам:
 *
 *  1. **Проверяемость.** Правило «в полёте показываем цель, на стоянке —
 *     где стоим» иначе не проверить: системы на карте выбираются тапом по
 *     канвасу, а тап в jsdom не срабатывает. Чистая функция проверяется
 *     обычным тестом, без подделки DOM.
 *  2. **Один источник правды.** Шапка рисуется в одном месте, а значит
 *     подписи «Карта»/«Курс» не разъедутся с логикой.
 *
 * Кредитов здесь нет намеренно: они есть на «Корабле», «Рынке» и
 * «Ангаре». Шапка показывает то, чего рядом нигде нет: корабль, место и
 * время карьеры.
 */
import { systemsOf, type GameState } from '../core/state.ts';

/** Название корабля игрока. Пока он один — константа. */
export const SHIP_NAME = 'Cobra Mk III';

export interface TopSegment {
  /** Мелкая подпись над значением */
  key: string;
  /** Значение */
  value: string;
}

/**
 * Время карьеры в человеческом виде — «3 ч 12 мин».
 *
 * Отдельно от `fmtDur` (тот про длительность полёта и знает секунды):
 * карьера измеряется часами, секунды в шапке только мигали бы. Нулевая
 * карьера показывается как «< 1 мин», а не «0 мин»: иначе она выглядит
 * поломкой, хотя это просто новая игра.
 */
export function fmtCareer(ms: number): string {
  const min = Math.floor(Math.max(0, ms) / 60000);
  if (min < 1) return '< 1 мин';
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h === 0) return `${m} мин`;
  return m > 0 ? `${h} ч ${m} мин` : `${h} ч`;
}

/**
 * Три сегмента шапки.
 *
 * Место — это ЦЕЛЬ полёта, если корабль летит, и система стоянки, если нет.
 * Патруль летит «в себя» (`to === from`), поэтому для него имя то же, что
 * у стоянки, — и это правильно: патруль не меняет систему.
 */
export function topSegments(state: GameState): TopSegment[] {
  const list = systemsOf(state.galaxy);
  const flying = state.flight;
  const place = flying ? list[flying.to].name : list[state.system].name;
  return [
    { key: 'Корабль', value: SHIP_NAME },
    { key: flying ? 'Курс' : 'Карта', value: place },
    { key: 'Журнал', value: fmtCareer(state.careerMs ?? 0) },
  ];
}
