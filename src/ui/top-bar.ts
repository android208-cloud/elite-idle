/**
 * §91: верхняя строка — только ЗНАЧЕНИЕ, без подписи.
 *
 * История правок, чтобы не ходить по кругу:
 *
 *  §89 — три колонки сразу («Корабль · Карта · Журнал»). Неверно: это
 *        перечень всего, а не ответ на вопрос текущего экрана.
 *  §90 — одна пара «подпись : значение» на каждую вкладку. Тоже неверно,
 *        и это видно на экране: слева заголовок «Корабль», справа надпись
 *        «КОРАБЛЬ» — одно и то же дважды. Заголовок экрана УЖЕ называет
 *        вкладку, подпись в шапке его дублирует.
 *  §91 — в шапке остаётся одно значение. Заголовок слева говорит, ГДЕ вы,
 *        значение справа — ЧТО здесь важно.
 *
 *        Корабль  → Cobra Mk III
 *        Карта    → LAVE          (в полёте — цель)
 *        Рынок    → 100.0 CR
 *        Ангар    → 100.0 CR
 *        Журнал   → 1 ч 12 мин
 *
 * Значения подобраны самодостаточными: `CR` читается как деньги, время —
 * как время, имя системы — как место. Подпись нужна была бы только там,
 * где значение двусмысленно, а таких нет.
 *
 * Модуль чистый (без DOM), чтобы правило проверялось тестом: системы на
 * карте выбираются тапом по канвасу, а тап в jsdom не срабатывает.
 */
import { systemsOf, type GameState } from '../core/state.ts';

/** Название корабля игрока. Пока он один — константа. */
export const SHIP_NAME = 'Cobra Mk III';

/** Вкладки, для которых шапка знает своё значение. */
export type TopTab = 'ship' | 'map' | 'market' | 'hangar' | 'log';

/**
 * Время карьеры в человеческом виде — «3 ч 12 мин».
 *
 * Отдельно от `fmtDur` (тот про длительность полёта и знает секунды):
 * карьера измеряется часами, секунды в шапке только мигали бы. Нулевая
 * карьера показывается как «< 1 мин», а не «0 мин»: иначе она выглядит
 * поломкой, хотя это просто новая игра.
 */
export function fmtCareer(ms: number): string {
  const min = Math.floor(Math.max(0, ms) / 60000);
  if (min < 1) return '< 1 мин';
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h === 0) return `${m} мин`;
  return m > 0 ? `${h} ч ${m} мин` : `${h} ч`;
}

/**
 * Кредиты в шапке — тем же форматом, что и везде в игре.
 *
 * Деньги хранятся в десятых долях кредита, поэтому делим на 10. Знак `CR`
 * оставляем: без него число в шапке читалось бы как что угодно.
 */
export function fmtCash(tenths: number): string {
  return `${(tenths / 10).toFixed(1)} CR`;
}

/**
 * Где корабль: цель полёта, если летим, иначе система стоянки.
 *
 * Патруль летит «в себя» (`to === from`), поэтому для него имя то же, что
 * у стоянки, — и это правильно: патруль не меняет систему.
 */
function placeOf(state: GameState): string {
  const list = systemsOf(state.galaxy);
  const flying = state.flight;
  return flying ? list[flying.to].name : list[state.system].name;
}

/**
 * Одно значение для текущего экрана.
 *
 * `null` вместо вкладки — бой или обломки: вкладок там нет, показываем
 * место. Это не заглушка, а честный ответ на «где я»: в бою не до
 * кредитов, но понимать, где находишься, всё ещё нужно.
 */
export function topValue(state: GameState, tab: TopTab | null): string {
  if (tab === null) return placeOf(state);
  switch (tab) {
    case 'ship':
      return SHIP_NAME;
    case 'map':
      return placeOf(state);
    case 'market':
    case 'hangar':
      return fmtCash(state.cash);
    case 'log':
      return fmtCareer(state.careerMs ?? 0);
  }
}
